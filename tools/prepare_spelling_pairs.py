"""Build tools/data/spelling_pairs_bn.tsv: real Latin spellings of common Bengali words.

Usage:
    python tools/prepare_spelling_pairs.py <ben_train.json> <bn_50k.txt>

ben_train.json is the Bengali training split of AI4Bharat Aksharantar (CC BY 4.0,
https://huggingface.co/datasets/ai4bharat/Aksharantar), which includes the Google Dakshina
lexicon (CC BY-SA 4.0). Each line pairs a Bengali word with a Latin spelling people wrote.

Only Bengali words in the 50k frequency list or tools/data/bn_wiki_extra.txt are kept, so the table stays small and
never brings in rare words. For each Latin spelling the Bengali word it was paired with most
often wins (ties: the more frequent word). Output lines: latin<TAB>bengali<TAB>rank.
"""
import collections
import json
import os
import re
import sys

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "spelling_pairs_bn.tsv")


def main(train_path, bn_path):
    rank = {}
    with open(bn_path, encoding="utf-8") as f:
        for i, line in enumerate(f):
            parts = line.split()
            if len(parts) == 2 and parts[0] not in rank:
                rank[parts[0]] = i
    # Wikipedia words (tools/data/bn_wiki_extra.txt) rank after the 50k list, as in the build.
    wiki_path = os.path.join(os.path.dirname(OUT), "bn_wiki_extra.txt")
    if os.path.exists(wiki_path):
        with open(wiki_path, encoding="utf-8") as f:
            for i, line in enumerate(f):
                parts = line.split()
                if len(parts) == 2 and parts[0] not in rank:
                    rank[parts[0]] = 60000 + i
    pairs = collections.defaultdict(collections.Counter)
    with open(train_path, encoding="utf-8") as f:
        for line in f:
            j = json.loads(line)
            latin, bengali = j["english word"].lower(), j["native word"]
            if bengali in rank and re.fullmatch(r"[a-z]+", latin):
                pairs[latin][bengali] += 1
    rows = []
    for latin, counts in pairs.items():
        bengali = max(counts, key=lambda b: (counts[b], -rank[b]))
        rows.append(f"{latin}\t{bengali}\t{rank[bengali]}")
    rows.sort()
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Latin spelling -> Bengali word -> frequency rank. Generated by\n"
                "# tools/prepare_spelling_pairs.py from AI4Bharat Aksharantar (CC BY 4.0), which\n"
                "# includes Google Dakshina (CC BY-SA 4.0).\n")
        f.write("\n".join(rows) + "\n")
    print(f"{len(rows)} spellings -> {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
